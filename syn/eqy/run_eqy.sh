# Equivalence of ibex_top's SystemVerilog (gold, read by yosys-slang) and its sv2v conversion
# (gate, the Verilog the synthesis flow reads), proven with EQY. Run inside
# `nix develop .#eqy_shell`.
#
#   eqy/run_eqy.sh [out_dir]
#
#   EQY_CHERIOT=1|0   BaseIsa RV32IorCHERIoT (default) or RV32I
#   EQY_MUTATE=1      break the gate's ALU adder first: the run must then report a difference
#   EQY_JOBS=<n>      parallel partitions (default: nproc)
#   EQY_DEPTH=<n>     k-induction depth per partition (default 5)
#   EQY_TIMEOUT=<s>   per-partition limit of the smtbmc strategy (default 300), then ABC PDR
#   EQY_ABC_TIMEOUT=<s>  per-partition limit of the ABC strategy (default 1800); a partition that
#                     neither strategy finishes is UNKNOWN, and so is the run
#
# The register file is the flip-flop one (RegFile=RegFileFF) and prim_clock_gating a pass-through
# on both sides (eqy/prim_clock_gating.v): the proof has one global clock and no latches.

set -e
set -o pipefail

cd "$(dirname "$0")/.."
: "${LOWRISC_YOSYS_SLANG:?not set: run inside nix develop .#eqy_shell}"

cheriot=${EQY_CHERIOT:-1}
if [ "$cheriot" = 1 ]; then
    base_isa_num=1; base_isa_name=ibex_pkg::BaseIsaRV32IorCHERIoT; tag=cheriot
else
    base_isa_num=0; base_isa_name=ibex_pkg::BaseIsaRV32I; tag=rv32i
fi
[ "${EQY_MUTATE:-0}" = 1 ] && tag=${tag}_mutated
out=${1:-eqy_out/ibex_top_${tag}_$(date +%Y%m%d_%H%M%S)}
mkdir -p "$out"
out=$(cd "$out" && pwd)

source ./sv2v_convert.sh
./sv2v_convert.sh "$out/generated"

skip='ibex_tracer|ibex_top_tracing|ibex_register_file_fpga|ibex_register_file_latch'

if [ "${EQY_MUTATE:-0}" = 1 ]; then
    alu="$out/generated/ibex_alu.v"
    sed -i 's/assign adder_result_ext_o = $unsigned(adder_in_a) + $unsigned(adder_in_b);/assign adder_result_ext_o = $unsigned(adder_in_a) ^ $unsigned(adder_in_b);/' "$alu"
    grep -q 'adder_result_ext_o = $unsigned(adder_in_a) ^ $unsigned(adder_in_b);' "$alu" || {
        echo "EQY_MUTATE: the ALU adder line was not found in $alu; nothing was mutated" >&2
        exit 1
    }
    echo "EQY_MUTATE: gate ALU adder changed from + to ^ (this run must FAIL)"
fi

gold_files=()
for f in "${LR_DEP_PKGS[@]}" "${LR_CORE_PKGS[@]}" "${LR_DEP_SOURCES[@]}" "${LR_CORE_SOURCES[@]}"; do
    [[ $(basename -s .sv "$f") =~ ^($skip)$ ]] || gold_files+=("$(realpath "$f")")
done
# Packages appear in both package lists; slang must see each file once.
mapfile -t gold_files < <(printf '%s\n' "${gold_files[@]}" | awk '!seen[$0]++')

gate_files=()
for f in "$out"/generated/*.v; do
    [[ $(basename -s .v "$f") =~ ^($skip)$ ]] || gate_files+=("$f")
done

incdirs=()
for d in "${LR_INCDIRS[@]}"; do incdirs+=("-I $(realpath "$d")"); done
cg=$(realpath eqy/prim_clock_gating.v)

# Match points are register outputs and ports only (rename -hide everything else, as EQY's own
# processor example does): slang and sv2v name and buffer combinational wires differently, and
# two names for one net (adder_result and adder_result_ext_o[32:1]) became independent partition
# inputs, a difference that cannot occur (ibex_alu: 3 false failures, none with this).
cat > "$out/ibex_top.eqy" <<EOF
# Generated by eqy/run_eqy.sh
[gold]
plugin -i $LOWRISC_YOSYS_SLANG
read_slang -D SYNTHESIS -D YOSYS ${incdirs[*]} --ignore-unknown-modules --top ibex_top -G BaseIsa=$base_isa_name -G RegFile=ibex_pkg::RegFileFF ${gold_files[*]} $cg
prep -top ibex_top
flatten
memory_map
rename -hide t:\$*ff* %co x:* %% w:* %D
opt_clean

[gate]
read_verilog -defer -sv ${gate_files[*]} $cg
chparam -set BaseIsa $base_isa_num ibex_top
chparam -set RegFile 0 ibex_top
prep -top ibex_top
flatten
memory_map
rename -hide t:\$*ff* %co x:* %% w:* %D
opt_clean

[strategy sby]
use sby
depth ${EQY_DEPTH:-5}
engine smtbmc yices
timeout ${EQY_TIMEOUT:-300}

# Tried for partitions the first strategy did not finish in time, in practice the multiplier
# bits: ABC handles two structurally similar multipliers far better than bit-level SMT.
[strategy abc]
use sby
engine abc pdr
timeout ${EQY_ABC_TIMEOUT:-1800}
EOF

echo "EQY config: $out/ibex_top.eqy"
set +e
eqy -j "${EQY_JOBS:-$(nproc)}" -f "$out/ibex_top.eqy" -d "$out/eqy" 2>&1 | tee "$out/eqy.log"
rc=${PIPESTATUS[0]}
set -e

# EQY leaves a file named after its verdict in the work directory.
status="NO VERDICT"
for s in PASS FAIL UNKNOWN TIMEOUT ERROR; do [ -f "$out/eqy/$s" ] && status=$s; done
echo "EQY ${tag}: ${status} (exit ${rc}); log: $out/eqy.log"
if [ "${EQY_MUTATE:-0}" = 1 ]; then
    # Only a proven difference counts: an ERROR or a crash is not a caught mutation.
    [ "$status" = FAIL ] && { echo "EQY_MUTATE: CAUGHT, the mutated gate was proven different"; exit 0; }
    echo "EQY_MUTATE: MISSED, verdict ${status} instead of FAIL" >&2
    exit 1
fi
[ "$status" = PASS ] || exit $(( rc == 0 ? 1 : rc ))
